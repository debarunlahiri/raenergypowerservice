function asset_list(string $folder): array
{
    $paths = glob(__DIR__ . '/../' . $folder . '/*.{jpg,jpeg,png,webp}', GLOB_BRACE) ?: [];
    sort($paths, SORT_NATURAL);

    return array_map(static fn ($path) => $folder . '/' . basename($path), $paths);
}

